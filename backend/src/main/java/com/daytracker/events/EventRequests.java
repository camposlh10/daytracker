package com.daytracker.events;

import java.time.DayOfWeek;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import jakarta.validation.constraints.NotNull;

/**
 * Create and update carry every editable field: an event can switch between
 * timed and all-day, so a partial update would leave it half of each.
 * A timed event gives {@code start} and {@code end} as wall-clock times in
 * {@code timezone}; an all-day event gives {@code startDate} and the exclusive
 * {@code endDateExclusive}. The fields of the other kind must be absent.
 * {@code repeat} is absent (once), {@code DAILY} with an optional
 * {@code repeatUntil}, {@code WEEKLY} with {@code repeatWeekdays} and an optional
 * {@code repeatUntil}, or {@code DATES} with {@code repeatDates}; {@code links}
 * are web addresses.
 */
public final class EventRequests {

	private EventRequests() {
	}

	public record Fields(String title, String notes, UUID categoryId, Boolean allDay, LocalDateTime start,
			LocalDateTime end, String timezone, LocalDate startDate, LocalDate endDateExclusive, String repeat,
			LocalDate repeatUntil, List<LocalDate> repeatDates, List<DayOfWeek> repeatWeekdays, List<String> links) {
	}

	/** The id is generated by the client so a retried create is idempotent. */
	public record Create(@NotNull UUID id, String title, String notes, UUID categoryId, Boolean allDay,
			LocalDateTime start, LocalDateTime end, String timezone, LocalDate startDate,
			LocalDate endDateExclusive, String repeat, LocalDate repeatUntil, List<LocalDate> repeatDates,
			List<DayOfWeek> repeatWeekdays, List<String> links) {

		Fields fields() {
			return new Fields(title, notes, categoryId, allDay, start, end, timezone, startDate, endDateExclusive,
					repeat, repeatUntil, repeatDates, repeatWeekdays, links);
		}

		/** An appointment that happens once and has no links. */
		public Create(UUID id, String title, String notes, UUID categoryId, Boolean allDay, LocalDateTime start,
				LocalDateTime end, String timezone, LocalDate startDate, LocalDate endDateExclusive) {
			this(id, title, notes, categoryId, allDay, start, end, timezone, startDate, endDateExclusive, null, null,
					null, null, null);
		}

	}

	public record Update(@NotNull Long version, String title, String notes, UUID categoryId, Boolean allDay,
			LocalDateTime start, LocalDateTime end, String timezone, LocalDate startDate,
			LocalDate endDateExclusive, String repeat, LocalDate repeatUntil, List<LocalDate> repeatDates,
			List<DayOfWeek> repeatWeekdays, List<String> links) {

		Fields fields() {
			return new Fields(title, notes, categoryId, allDay, start, end, timezone, startDate, endDateExclusive,
					repeat, repeatUntil, repeatDates, repeatWeekdays, links);
		}

		/** An appointment that happens once and has no links. */
		public Update(Long version, String title, String notes, UUID categoryId, Boolean allDay, LocalDateTime start,
				LocalDateTime end, String timezone, LocalDate startDate, LocalDate endDateExclusive) {
			this(version, title, notes, categoryId, allDay, start, end, timezone, startDate, endDateExclusive, null, null,
					null, null, null);
		}

	}

}
